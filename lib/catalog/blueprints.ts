export function blueprintById(id: string): Blueprint | undefined {
  return BLUEPRINTS.find((item) => item.id === id);
}

export function bundleById(id: string): BlueprintBundle | undefined {
  return BUNDLES.find((item) => item.id === id);
}

export function normalizeServiceName(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, " ");
}

/** Blueprints that already match a service in this workspace, by stamped id or by name. */
export function blueprintIdsInCatalog(
  services: Array<Pick<ServiceRecord, "name" | "custom_fields">>,
): Set<string> {
  const names = new Set(services.map((service) => normalizeServiceName(service.name)));
  const matched = new Set<string>();
  for (const service of services) {
    const stamped = service.custom_fields?.blueprint_id;
    if (typeof stamped === "string") matched.add(stamped);
  }
  for (const blueprint of BLUEPRINTS) {
    if (names.has(normalizeServiceName(blueprint.name))) matched.add(blueprint.id);
  }
  return matched;
}

export function filterBlueprints(args: {
  query: string;
  aisle: AisleId | "all";
  bundleId: string | "all";
}): Blueprint[] {
  const bundle = args.bundleId === "all" ? null : bundleById(args.bundleId);
  const allowed = bundle ? new Set(bundle.blueprintIds) : null;
  const needle = args.query.trim().toLowerCase();
  return BLUEPRINTS.filter((blueprint) => {
    if (args.aisle !== "all" && blueprint.aisle !== args.aisle) return false;
    if (allowed && !allowed.has(blueprint.id)) return false;
    if (!needle) return true;
    const haystack = [blueprint.name, blueprint.summary, blueprint.category, blueprint.aisle, blueprint.primary_csf_function]
      .join(" ")
      .toLowerCase();
    return haystack.includes(needle);
  });
}

export function blueprintIssues(lookups: LookupSeed[]): string[] {
  const issues: string[] = [];
  const codes = new Map<string, Set<string>>();
  for (const row of lookups) {
    const set = codes.get(row.field_key) ?? new Set<string>();
    set.add(row.code);
    codes.set(row.field_key, set);
  }
  const has = (field: string, code: string) => codes.get(field)?.has(code) ?? false;
  const ids = new Set<string>();
  const names = new Set<string>();
  if (BLUEPRINTS.length < 48 || BLUEPRINTS.length > 55) {
    issues.push(`Expected 48–55 blueprints, found ${BLUEPRINTS.length}.`);
  }
  for (const blueprint of BLUEPRINTS) {
    if (ids.has(blueprint.id)) issues.push(`Duplicate id ${blueprint.id}.`);
    ids.add(blueprint.id);
    const nameKey = normalizeServiceName(blueprint.name);
    if (names.has(nameKey)) issues.push(`Duplicate name ${blueprint.name}.`);
    names.add(nameKey);
    if (!AISLES.some((aisle) => aisle.id === blueprint.aisle)) issues.push(`${blueprint.id} has an unknown aisle.`);
    if (!has("category", blueprint.category)) issues.push(`${blueprint.id} category ${blueprint.category}`);
    if (!has("service_tier", blueprint.service_tier)) issues.push(`${blueprint.id} tier`);
    if (!has("primary_csf_function", blueprint.primary_csf_function)) issues.push(`${blueprint.id} csf`);
    if (!has("intake_method", blueprint.intake_method)) issues.push(`${blueprint.id} intake`);
    if (!has("hours_of_coverage", blueprint.hours_of_coverage)) issues.push(`${blueprint.id} hours`);
    if (!has("data_classification", blueprint.data_classification_handled)) issues.push(`${blueprint.id} classification`);
    if (!has("review_cadence", blueprint.review_cadence)) issues.push(`${blueprint.id} cadence`);
    if (!has("delivery_model", blueprint.delivery_model)) issues.push(`${blueprint.id} delivery model`);
    if (!has("team", blueprint.suggested_owner_team)) issues.push(`${blueprint.id} owner team`);
    if (!has("team", blueprint.suggested_delivery_team)) issues.push(`${blueprint.id} delivery team`);
    for (const audience of blueprint.target_audience) {
      if (!has("target_audience", audience)) issues.push(`${blueprint.id} audience ${audience}`);
    }
    const texts: Array<[string, string]> = [
      ["summary", blueprint.summary],
      ["deliverables", blueprint.deliverables],
      ["out_of_scope", blueprint.out_of_scope],
      ["prerequisites", blueprint.prerequisites],
      ["lead_time", blueprint.lead_time],
      ["sla_response", blueprint.sla_response_target],
      ["sla_resolution", blueprint.sla_resolution_target],
      ["escalation", blueprint.escalation_path],
      ["threats", blueprint.threats_addressed],
      ["kpis", blueprint.kpis_and_metrics],
      ["description", blueprint.description],
      ["in_scope", blueprint.in_scope],
    ];
    for (const [label, value] of texts) {
      if (value.trim().length < 24) issues.push(`${blueprint.id} ${label} is thin.`);
    }
    if (blueprint.nist_csf.length === 0) issues.push(`${blueprint.id} missing NIST hint.`);
    if (blueprint.approval_required && !blueprint.approver) issues.push(`${blueprint.id} approval has no approver role.`);
  }
  for (const bundle of BUNDLES) {
    const unique = new Set(bundle.blueprintIds);
    if (unique.size !== bundle.blueprintIds.length) issues.push(`${bundle.id} repeats a blueprint.`);
    for (const id of bundle.blueprintIds) {
      if (!ids.has(id)) issues.push(`${bundle.id} references missing ${id}.`);
    }
  }
  const small = BUNDLES.find((bundle) => bundle.id === "size-small");
  const medium = BUNDLES.find((bundle) => bundle.id === "size-medium");
  const large = BUNDLES.find((bundle) => bundle.id === "size-large");
  if (!small || small.blueprintIds.length < 10 || small.blueprintIds.length > 12) issues.push("Small pack size.");
  if (!medium || medium.blueprintIds.length < 22 || medium.blueprintIds.length > 26) issues.push("Medium pack size.");
  if (!large || large.blueprintIds.length < 38 || large.blueprintIds.length > 45) issues.push("Large pack size.");
  return issues;
}

