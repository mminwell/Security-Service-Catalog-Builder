const PUBLIC_FIELD_KEYS = new Set(["name", "summary"]);

export const STARTER_FIELDS: FieldSeed[] = RAW.map((field, index) => ({
  ...field,
  sort_order: (index + 1) * 10,
  visibility: PUBLIC_FIELD_KEYS.has(field.field_key) ? "public" : "internal",
}));

export function materializeFields(tenantId: string | null, idFor: (fieldKey: string) => string): FieldDefinition[] {
  return STARTER_FIELDS.map((field) => ({
    id: idFor(field.field_key),
    tenant_id: tenantId,
    field_key: field.field_key,
    label: field.label,
    help_text: field.help_text,
    input_type: field.input_type,
    lookup_field_key: field.lookup_field_key,
    lookup_bound: false,
    lookup_restore: null,
    visibility_overridden: false,
    is_required: field.is_required,
    visibility: field.visibility,
    depth_level: field.depth_level,
    sort_order: field.sort_order,
    is_active: field.is_active !== false,
    is_standard: true,
    field_group: field.field_group ?? null,
  }));
}

export const REQUIRED_FIELD_KEYS = STARTER_FIELDS.filter((field) => field.is_required).map(
  (field) => field.field_key,
);

const IDENTITY_FIELD_KEYS = new Set(["service_code", "name"]);

/** Service code and name stay active so a catalog entry cannot become nameless or codeless. */
export function isIdentityField(fieldKey: string): boolean {
  return IDENTITY_FIELD_KEYS.has(fieldKey);
}
